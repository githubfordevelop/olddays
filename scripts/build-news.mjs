// Rebuild the browser's offline reading library from the attributed editorial data.
import { readFileSync, writeFileSync } from "node:fs";
const articles = JSON.parse(readFileSync("data/news-articles.json", "utf8"));
const seen = new Set();
for (const article of articles) {
  if (seen.has(article.id)) throw Error("Duplicate story: " + article.id);
  seen.add(article.id);
  if (
    !/^\d{4}-\d+$/.test(article.id) ||
    !Number.isSafeInteger(article.revision)
  )
    throw Error("Invalid story provenance");
  if (
    !article.source.startsWith("https://zh.wikipedia.org/w/index.php?oldid=") ||
    !article.sections?.length
  )
    throw Error("Missing source or body");
  if (article.sections.flatMap((s) => s.paragraphs).join("").length < 750)
    throw Error("Story still too short: " + article.id);
}
const header =
  "/* Historical reading excerpts: Wikipedia contributors, CC BY-SA 4.0. See docs/NEWS-LICENSE.md. Generated by scripts/build-news.mjs. */\n";
const runtime = `const researchedArticles = ${JSON.stringify(articles)};\nfor (const article of researchedArticles) {\n  const [year, index] = article.id.split('-');\n  const original = eventDetails[article.id];\n  const brief = original?.paragraphs ? {title:'当年事件', paragraphs:original.paragraphs, source:original.source || yearEvents[year][Number(index)]?.[2] || CHRONICLE} : null;\n  yearEvents[year][Number(index)] = [article.date, article.title, article.source, '维基百科 · 历史资料版'];\n  eventDetails[article.id] = {...article, sections: brief ? [brief, ...article.sections] : article.sections};\n}\n`;
writeFileSync("dist/news-articles.js", header + runtime);
writeFileSync(
  "docs/article-sources.json",
  JSON.stringify(
    articles.map(
      ({
        id,
        title,
        topic,
        source,
        history,
        revision,
        retrieved,
        sources,
      }) => ({
        id,
        title,
        topic,
        source,
        history,
        revision,
        retrieved,
        sources,
        attribution: "Wikipedia contributors",
        license: "CC BY-SA 4.0",
        modifications: "简体转换、段落节选与编排",
      }),
    ),
    null,
    2,
  ) + "\n",
);
console.log(`Built ${articles.length} attributed offline reading pages.`);
